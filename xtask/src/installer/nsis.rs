// ./xtask/src/installer/nsis.rs
//! Windows setup executable via NSIS.
//!
//! The setup does not carry install logic of its own. It unpacks the release bundle to a temporary
//! directory and runs `pyenv self-install` from there, exactly like `install.ps1` and
//! `pyenv self-update` do. That keeps one layout (`%USERPROFILE%\.pyenv` by default), so:
//!
//! * installs made by earlier releases are upgraded in place (the existing root is detected);
//! * the in-app updater keeps working after a setup-based install;
//! * "Apps & features" is populated by `self-install` itself, and its uninstall command is
//!   `pyenv self-uninstall`, so the setup ships no second uninstaller to keep in sync.
//!
//! The setup runs per-user and never asks for elevation.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::{Context, Result, bail};

use super::{Bundle, Manifest};

const TEMPLATE: &str = r#"; Generated by `cargo xtask installer nsis`; do not edit.
Unicode true
ManifestDPIAware true
SetCompressor /SOLID lzma
!include "MUI2.nsh"
!include "LogicLib.nsh"

Name "Pyenv Native"
OutFile "@OUTFILE@"
RequestExecutionLevel user
InstallDir "$PROFILE\.pyenv"
BrandingText "pyenv-native @VERSION@"

VIProductVersion "@VERSION_QUAD@"
VIAddVersionKey "ProductName" "Pyenv Native"
VIAddVersionKey "FileDescription" "Pyenv Native Setup"
VIAddVersionKey "FileVersion" "@VERSION@"
VIAddVersionKey "ProductVersion" "@VERSION@"
VIAddVersionKey "LegalCopyright" "MIT License"

!define ARP_KEY "Software\Microsoft\Windows\CurrentVersion\Uninstall\pyenv-native"
!define MUI_ICON "@ICON@"
!define MUI_ABORTWARNING
!define MUI_WELCOMEPAGE_TITLE "Pyenv Native @VERSION@"
!define MUI_WELCOMEPAGE_TEXT "This installs pyenv-native for your user account. No administrator rights are needed.$\r$\n$\r$\nIf pyenv-native is already installed, it is upgraded in place and your Python versions are kept."
@FINISH_RUN@
!insertmacro MUI_PAGE_WELCOME
@LICENSE_PAGE@
!insertmacro MUI_PAGE_DIRECTORY
!insertmacro MUI_PAGE_INSTFILES
!insertmacro MUI_PAGE_FINISH
!insertmacro MUI_LANGUAGE "English"

; Upgrade the existing install instead of creating a second one. An explicit /D= wins.
Function .onInit
  StrCmp $INSTDIR "$PROFILE\.pyenv" 0 done
  ReadRegStr $0 HKCU "${ARP_KEY}" "InstallLocation"
  ${If} $0 == ""
    ReadEnvStr $0 PYENV_ROOT
  ${EndIf}
  ${If} $0 != ""
    StrCpy $INSTDIR $0
  ${EndIf}
  done:
FunctionEnd

Section "Install"
  InitPluginsDir
  SetOutPath "$PLUGINSDIR\bundle"
  File /r "@BUNDLE_GLOB@"
  DetailPrint "Installing pyenv-native into $INSTDIR"
  nsExec::ExecToLog '"$PLUGINSDIR\bundle\pyenv.exe" self-install --install-root "$INSTDIR" --source-dir "$PLUGINSDIR\bundle" --shell pwsh --add-to-user-path true --update-shell-profile true --install-powershell7 false --yes --force'
  Pop $0
  ${If} $0 != 0
    MessageBox MB_ICONSTOP|MB_OK "pyenv-native setup failed (exit code $0). See the details above." /SD IDOK
    SetErrorLevel $0
    Abort
  ${EndIf}
SectionEnd
"#;

/// `1.2.3-rc.1` -> `1.2.3.0` (NSIS wants exactly four numeric fields).
pub(crate) fn version_quad(version: &str) -> String {
    let core = version.split(['-', '+']).next().unwrap_or(version);
    let mut parts: Vec<String> = core
        .split('.')
        .map(|part| {
            part.chars()
                .take_while(char::is_ascii_digit)
                .collect::<String>()
        })
        .map(|part| {
            if part.is_empty() {
                "0".to_string()
            } else {
                part
            }
        })
        .collect();
    parts.resize(4, "0".to_string());
    parts.truncate(4);
    parts.join(".")
}

pub(crate) struct Inputs<'a> {
    pub manifest: &'a Manifest,
    pub bundle_dir: &'a Path,
    pub outfile: &'a Path,
    pub icon: &'a Path,
    pub license: Option<&'a Path>,
}

pub(crate) fn render(inputs: &Inputs<'_>) -> String {
    let finish_run = if inputs.manifest.gui {
        "!define MUI_FINISHPAGE_RUN \"$INSTDIR\\bin\\pyenv-gui.exe\"\n!define MUI_FINISHPAGE_RUN_TEXT \"Launch Pyenv Native\"".to_string()
    } else {
        String::new()
    };
    let license_page = inputs
        .license
        .map(|path| format!("!insertmacro MUI_PAGE_LICENSE \"{}\"", path.display()))
        .unwrap_or_default();
    TEMPLATE
        .replace("@OUTFILE@", &inputs.outfile.display().to_string())
        .replace("@VERSION_QUAD@", &version_quad(&inputs.manifest.version))
        .replace("@VERSION@", &inputs.manifest.version)
        .replace("@ICON@", &inputs.icon.display().to_string())
        .replace("@FINISH_RUN@", &finish_run)
        .replace("@LICENSE_PAGE@", &license_page)
        .replace(
            "@BUNDLE_GLOB@",
            &format!(
                "{}{}*",
                inputs.bundle_dir.display(),
                if cfg!(windows) { '\\' } else { '/' }
            ),
        )
}

pub(crate) fn write(
    bundle: &Bundle,
    output_root: &Path,
    makensis: &str,
    script_only: bool,
) -> Result<PathBuf> {
    fs::create_dir_all(output_root)?;
    let output_root = fs::canonicalize(output_root)?;
    let manifest = &bundle.manifest;
    let outfile = output_root.join(format!(
        "pyenv-native-windows-{}-setup.exe",
        manifest.architecture
    ));
    let icon = crate::repo_root()
        .join("crates")
        .join("pyenv-gui")
        .join("icons")
        .join("icon.ico");
    if !icon.is_file() {
        bail!("installer icon not found at {}", icon.display());
    }
    let license = bundle.path().join("LICENSE");
    let script = render(&Inputs {
        manifest,
        bundle_dir: bundle.path(),
        outfile: &outfile,
        icon: &icon,
        license: license.is_file().then_some(license.as_path()),
    });

    if script_only {
        let path = output_root.join(format!(
            "pyenv-native-windows-{}.nsi",
            manifest.architecture
        ));
        fs::write(&path, script)?;
        return Ok(path);
    }

    // Outside the bundle directory, which the script embeds wholesale.
    let script_dir = tempfile::tempdir().context("cannot create a script directory")?;
    let script_path = script_dir.path().join("setup.nsi");
    fs::write(&script_path, script)?;
    let _ = fs::remove_file(&outfile);
    let status = Command::new(makensis)
        .args(["-V2", "-INPUTCHARSET", "UTF8"])
        .arg(&script_path)
        .status()
        .with_context(|| {
            format!(
                "failed to run `{makensis}`; install NSIS (apt install nsis / choco install nsis)"
            )
        })?;
    if !status.success() {
        bail!("makensis failed ({status})");
    }
    if !outfile.is_file() {
        bail!(
            "makensis reported success but {} was not written",
            outfile.display()
        );
    }
    Ok(outfile)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn manifest(gui: bool) -> Manifest {
        Manifest {
            version: "1.2.3-rc.1".into(),
            platform: "windows".into(),
            architecture: "x64".into(),
            gui,
        }
    }

    fn script(gui: bool, license: Option<&Path>) -> String {
        render(&Inputs {
            manifest: &manifest(gui),
            bundle_dir: Path::new("/stage/bundle"),
            outfile: Path::new("/out/setup.exe"),
            icon: Path::new("/repo/icon.ico"),
            license,
        })
    }

    #[test]
    fn versions_become_four_numeric_fields() {
        assert_eq!(version_quad("1.2.3"), "1.2.3.0");
        assert_eq!(version_quad("1.2.3-rc.1"), "1.2.3.0");
        assert_eq!(version_quad("2.0"), "2.0.0.0");
    }

    #[test]
    fn setup_runs_self_install_per_user_from_the_unpacked_bundle() {
        let text = script(true, None);
        assert!(text.contains("RequestExecutionLevel user"));
        assert!(text.contains(
            "self-install --install-root \"$INSTDIR\" --source-dir \"$PLUGINSDIR\\bundle\""
        ));
        assert!(text.contains("--yes --force"));
        assert!(text.contains("--install-powershell7 false"));
    }

    #[test]
    fn existing_installs_are_upgraded_in_place() {
        let text = script(true, None);
        assert!(text.contains("ReadRegStr $0 HKCU \"${ARP_KEY}\" \"InstallLocation\""));
        assert!(text.contains("ReadEnvStr $0 PYENV_ROOT"));
    }

    #[test]
    fn setup_ships_no_second_uninstaller() {
        let text = script(true, None);
        assert!(!text.contains("WriteUninstaller"));
        assert!(!text.contains("WriteRegStr"));
    }

    #[test]
    fn gui_launch_and_license_pages_are_conditional() {
        assert!(script(true, None).contains("MUI_FINISHPAGE_RUN"));
        assert!(!script(false, None).contains("MUI_FINISHPAGE_RUN"));
        assert!(
            script(false, Some(Path::new("/stage/LICENSE")))
                .contains("MUI_PAGE_LICENSE \"/stage/LICENSE\"")
        );
        assert!(!script(false, None).contains("MUI_PAGE_LICENSE"));
    }

    #[test]
    fn no_placeholder_survives_rendering() {
        assert!(!script(true, Some(Path::new("/l"))).contains('@'));
        let text = script(true, None);
        assert!(text.contains("InitPluginsDir"));
        assert!(
            text.contains("File /r \"/stage/bundle/*\"")
                || text.contains("File /r \"/stage/bundle\\*\"")
        );
    }
}
